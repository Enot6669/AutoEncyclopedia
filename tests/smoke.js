const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../assets');
const elements={},memory={};
const canvas=new Proxy({}, {get:(t,k)=>t[k]??(()=>{})});
const get=id=>elements[id]??={innerHTML:'',textContent:'',value:'',clientWidth:380,clientHeight:360,getContext:()=>canvas,addEventListener(){},insertAdjacentHTML(pos,s){this.innerHTML+=s}};
const sandbox=vm.createContext({document:{getElementById:get,querySelector:()=>null},window:{scrollTo(){},devicePixelRatio:1},localStorage:{getItem:k=>memory[k]??null,setItem:(k,v)=>memory[k]=v}});
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map(m=>fs.readFileSync(path.join(root,m[1]),'utf8'));
vm.runInContext(scripts.join('\n')+'\n'+html.split('<script>').pop().split('</script>')[0],sandbox);
const run=code=>vm.runInContext(code,sandbox);
assert(run('DATA.length')>=83);
assert.equal(run('new Set(DATA.map(x=>x.id)).size'),run('DATA.length'));
for(const file of run('Object.values(PHOTOS).map(p=>p.file)'))assert(fs.existsSync(path.join(root,file)),file);
run("changeCar('niva'); changeModel('21213 (карбюратор)'); goto('map'); showAtlas()");
assert(run('atlasState.hits.length')>100);
assert(run('atlasState.parts.every(p=>!p.id||DATA.some(a=>a.id===p.id))'));
run("atlasPreset('bottom'); atlasSelect('fuel-lines','Подача топлива')");
assert.equal(run('atlasState.layers.body'),false);
assert(get('atlasSelection').innerHTML.includes('Открыть карточку'));
run("changeCar('datsun'); goto('map'); showAtlas()");
assert(run("atlasState.parts.some(p=>p.id==='datsun-cv')&&!atlasState.parts.some(p=>p.id==='niva-transfer')"));
run("openCard('fastener-catalog')");
assert(get('main').innerHTML.includes('16,0–22,6'));
run("openCard('service-fuse')");
assert(get('main').innerHTML.includes('Съёмник предохранителей'));
const manifest=fs.readFileSync(path.join(root,'../AndroidManifest.xml'),'utf8');
assert(!manifest.includes('android.permission.INTERNET'));
console.log('Offline atlas, article links, photo assets, model filtering, workshop and manifest checks passed.');
